#!/usr/bin/env python3
"""Writes the German district keys the app checks a region against (#349).

A stored region key has to name a district for the warnings to be placed.
Checking only its first two digits let most postcodes through: "04109"
(Leipzig) begins like Bremen. The district table knows the 401 real keys,
but it is a third of a megabyte loaded from the bundle, and the region
filter is a plain value read in the background isolate. So the keys are
written out as a constant once more, from the same table.

Run it after tool/dwd_warncells.py, which writes the table:

    tool/german_district_keys.py

`test/features/warnings/region_key_test.dart` fails while the two differ.
"""

import sys

SOURCE = "preppsuite_flutter/assets/dwd_warncells.csv"
TARGET = "preppsuite_flutter/lib/features/warnings/application/german_district_keys.dart"


def main() -> int:
    keys = set()
    with open(SOURCE, encoding="utf-8") as table:
        for line in table:
            if line.startswith("#"):
                continue
            fields = line.rstrip("\n").split(";")
            if len(fields) >= 2 and fields[1]:
                keys.add(fields[1])
    if len(keys) < 300:
        print(f"only {len(keys)} district keys in {SOURCE}", file=sys.stderr)
        return 1

    lines = [
        "// Generated by tool/german_district_keys.py from",
        "// assets/dwd_warncells.csv -- do not edit.",
        "",
        "/// The five-digit key of every German district (Kreis and kreisfreie",
        "/// Stadt), as the DWD's warncell table lists them (#349).",
        "const germanDistrictKeys = <String>{",
    ]
    lines += [f"  '{key}'," for key in sorted(keys)]
    lines += ["};", ""]
    with open(TARGET, "w", encoding="utf-8") as out:
        out.write("\n".join(lines))
    print(f"{len(keys)} district keys -> {TARGET}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
